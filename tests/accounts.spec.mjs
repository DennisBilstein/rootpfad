import { test, expect } from '@playwright/test';
import { spawn } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import Database from 'better-sqlite3';

test('Anmeldung, Rollen, Einladung, Kontentrennung, Synchronisation und Ampel', async ({ browser, playwright }) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(),'rootpfad-auth-test-'));
  const server = spawn(process.execPath,['server.mjs'],{env:{...process.env,PORT:'5189',ROOTPFAD_DATA_DIR:dir,MAIL_MODE:'development',PUBLIC_BASE_URL:'http://127.0.0.1:5189'},stdio:['ignore','pipe','pipe']});
  try {
    const setupToken = await new Promise((resolve,reject) => {
      let log=''; const timer=setTimeout(()=>reject(Error('Testserver startet nicht')),15000);
      server.stdout.on('data',chunk=>{log+=chunk;const match=log.match(/#setup=([a-f0-9]{64})/);if(match){clearTimeout(timer);resolve(match[1]);}});
      server.once('exit',code=>{clearTimeout(timer);reject(Error('Server beendet: '+code));});
    });
    const baseURL='http://127.0.0.1:5189';
    const admin=await playwright.request.newContext({baseURL});
    const guest=await playwright.request.newContext({baseURL});
    expect((await guest.get('/api/progress')).status()).toBe(401);
    expect((await admin.post('/api/setup',{data:{token:setupToken,name:'Test Admin',email:'admin@example.test',password:'test-password-long'}})).ok()).toBe(true);
    expect((await guest.post('/api/setup',{data:{token:setupToken}})).status()).toBe(403);
    const invite=await (await admin.post('/api/admin/invites',{data:{}})).json();
    const participant=await playwright.request.newContext({baseURL});
    const registration=await participant.post('/api/register',{data:{token:invite.token,name:'Test Teilnehmer',email:'learner@example.test',password:'test-password-long',role:'admin'}});
    expect((await registration.json()).user.role).toBe('participant');
    expect((await participant.put('/api/progress',{headers:{'X-Rootpfad-User':'-1'},data:{data:{},learningPath:'all'}})).status()).toBe(409);
    expect((await participant.get('/api/admin/participants')).status()).toBe(403);
    expect((await participant.get('/api/admin/assessments')).status()).toBe(403);
    expect((await participant.put('/api/progress',{data:{data:{stats:{bad:{right:'NaN',wrong:0}}},learningPath:'all'}})).status()).toBe(400);
    expect((await participant.put('/api/progress',{data:{data:{competencies:{feedback:{bad:{note:{nested:true}}}}},learningPath:'all'}})).status()).toBe(400);
    expect((await participant.post('/api/admin/invites',{data:{}})).status()).toBe(403);
    expect((await guest.post('/api/register',{data:{token:invite.token,name:'Noch einer',email:'other@example.test',password:'test-password-long'}})).status()).toBe(403);
    let overview=await (await admin.get('/api/admin/participants')).json();
    expect(overview.participants[0].light).toBe('gray');
    const context=await browser.newContext({storageState:await participant.storageState()});
    const page=await context.newPage(); await page.goto(baseURL);
    await page.waitForFunction(()=>window.RP_APP_READY && rpSyncReady);
    await page.evaluate(async()=>{rpChoosePath('abap');state.completed.add('abap-m1-l1');await saveProgress();await rpSync();});
    await expect.poll(async()=>{
      const progress=await (await participant.get('/api/progress')).json();return progress.data?.completed?.includes('abap-m1-l1');
    }).toBe(true);
    overview=await (await admin.get('/api/admin/participants')).json();
    expect(overview.participants[0].summary.path).toBe('abap');
    expect(overview.participants[0].summary.completed).toBe(1);
    const activity=overview.participants[0].activity;
    const data=(await (await participant.get('/api/progress')).json()).data;
    await participant.put('/api/progress',{data:{data,learningPath:'java'}});
    overview=await (await admin.get('/api/admin/participants')).json();
    expect(overview.participants[0].activity).toBe(activity);
    const id=overview.participants[0].id;
    const submission={moduleId:'m52',revision:'assessment-v1',ts:Date.now(),status:'accepted',normal:'normal case',boundary:'boundary case',failure:'failure case',evidence:'test evidence',help:'none'};
    await participant.put('/api/progress',{data:{data:{...data,competencies:{submissions:{m52:submission},variants:{},feedback:{}}},learningPath:'php'}});
    const uploaded=await (await participant.get('/api/progress')).json();expect(uploaded.data.competencies.submissions.m52.status).toBe('submitted');
    expect((await admin.put('/api/admin/assessments/'+id+'/m52',{data:{status:'accepted',note:'Alle drei Fälle nachvollziehbar geprüft.',submittedAt:submission.ts}})).ok()).toBe(true);
    expect((await (await participant.get('/api/progress')).json()).data.competencies.submissions.m52.status).toBe('accepted');
    await admin.put('/api/admin/participants/'+id,{data:{paused:true}});
    expect((await (await admin.get('/api/admin/participants')).json()).participants[0].light).toBe('gray');
    expect((await participant.get('/api/progress?user_id=1')).ok()).toBe(true);
    expect((await (await admin.get('/api/progress')).json()).data).toBeNull();
    expect((await participant.put('/api/progress',{headers:{Origin:'https://evil.example'},data:{data,learningPath:'all'}})).status()).toBe(403);
    const other=await browser.newContext(); const clean=await other.newPage();await clean.goto(baseURL);await clean.waitForFunction(()=>window.RP_APP_READY);
    expect(await clean.evaluate(()=>state.completed.has('abap-m1-l1'))).toBe(false);
    const exported=await participant.get('/api/account/export');expect(exported.ok()).toBe(true);
    expect((await participant.get('/api/account/export',{headers:{'X-Rootpfad-User':'-1'}})).status()).toBe(409);
    const personal=await exported.json();expect(personal.account.email).toBe('learner@example.test');expect(JSON.stringify(personal)).not.toContain('rp_session');expect(personal.account.password).toBeUndefined();
    const secondSession=await playwright.request.newContext({baseURL});
    expect((await secondSession.post('/api/login',{data:{email:'learner@example.test',password:'test-password-long'}})).ok()).toBe(true);
    expect((await participant.post('/api/account/password',{data:{currentPassword:'wrong-password',newPassword:'different-long-password'}})).status()).toBe(403);
    expect((await participant.post('/api/account/password',{data:{currentPassword:'test-password-long',newPassword:'different-long-password'}})).ok()).toBe(true);
    expect((await secondSession.get('/api/progress')).status()).toBe(401);
    expect((await participant.get('/api/me')).ok()).toBe(true);
    await secondSession.dispose();
    const publicAsset=await guest.get('/assets/script-01.js',{headers:{'Accept-Encoding':'gzip'}});expect(publicAsset.headers()['content-encoding']).toBe('gzip');
    const privateExport=await participant.get('/api/account/export',{headers:{'Accept-Encoding':'gzip'}});expect(privateExport.headers()['content-encoding']).toBeUndefined();
    const knownReset=await guest.post('/api/password/request',{data:{email:'learner@example.test'}});
    const unknownReset=await guest.post('/api/password/request',{data:{email:'unknown@example.test'}});
    expect(await knownReset.json()).toEqual(await unknownReset.json());
    const previewDirectory=path.join(dir,'mail-preview');
    const preview=JSON.parse(fs.readFileSync(path.join(previewDirectory,fs.readdirSync(previewDirectory)[0]),'utf8'));
    const resetToken=new URLSearchParams(new URL(preview.resetURL).hash.slice(1)).get('reset');
    const recoveryContext=await browser.newContext();const recoveryPage=await recoveryContext.newPage();
    await recoveryPage.goto(baseURL+'/#reset='+resetToken);await recoveryPage.waitForFunction(()=>window.RP_APP_READY);
    await expect(recoveryPage.getByRole('heading',{name:'Neues Passwort setzen'})).toBeVisible();
    expect(new URL(recoveryPage.url()).hash).toBe('');
    await recoveryContext.close();
    const inspection=new Database(path.join(dir,'rootpfad.sqlite'));
    const resetRow=inspection.prepare('SELECT * FROM password_resets').get();
    expect(resetRow.token).not.toBe(resetToken);
    inspection.prepare('UPDATE password_resets SET expires=?').run(Date.now()-1000);
    expect((await guest.post('/api/password/reset',{data:{token:resetToken,password:'recovered-long-password'}})).status()).toBe(400);
    inspection.prepare('UPDATE password_resets SET expires=?,password_version=?').run(resetRow.expires,'invalid-version');
    expect((await guest.post('/api/password/reset',{data:{token:resetToken,password:'recovered-long-password'}})).status()).toBe(400);
    inspection.prepare('UPDATE password_resets SET password_version=?').run(resetRow.password_version);inspection.close();
    expect((await guest.post('/api/password/reset',{data:{token:resetToken,password:'recovered-long-password'}})).ok()).toBe(true);
    expect((await guest.post('/api/password/reset',{data:{token:resetToken,password:'another-long-password'}})).status()).toBe(400);
    expect((await participant.get('/api/progress')).status()).toBe(401);
    expect((await participant.post('/api/login',{data:{email:'learner@example.test',password:'recovered-long-password'}})).ok()).toBe(true);
    expect((await admin.post('/api/account/delete',{data:{password:'test-password-long',confirmation:'KONTO LÖSCHEN'}})).status()).toBe(409);
    expect((await participant.post('/api/account/delete',{data:{password:'wrong',confirmation:'KONTO LÖSCHEN'}})).status()).toBe(403);
    const deletionContext=await browser.newContext({storageState:await participant.storageState()});
    const deletionPage=await deletionContext.newPage();await deletionPage.goto(baseURL);await deletionPage.waitForFunction(()=>window.RP_APP_READY&&window.rpAccount);
    await deletionPage.evaluate(()=>selectLesson('account-settings'));
    await deletionPage.getByRole('button',{name:'Löschvorgang öffnen'}).click();
    await deletionPage.getByLabel('Aktuelles Passwort',{exact:true}).fill('recovered-long-password');
    await deletionPage.getByLabel('Tippe KONTO LÖSCHEN').fill('KONTO LÖSCHEN');
    await deletionPage.getByRole('button',{name:'Konto unwiderruflich aus aktivem System löschen'}).click();
    await expect(deletionPage.getByRole('status').filter({hasText:'Konto und zugehöriger aktiver Serverlernstand gelöscht'})).toBeVisible();
    expect(await deletionPage.evaluate(id=>localStorage.getItem('rootpfad-user-'+id+'-progress'),id)).toBeNull();
    await deletionContext.close();
    expect((await participant.get('/api/progress')).status()).toBe(401);
    expect((await (await admin.get('/api/admin/participants')).json()).participants).toEqual([]);
    await context.close();await other.close();await admin.dispose();await guest.dispose();await participant.dispose();
  } finally { server.kill('SIGTERM'); }
});
